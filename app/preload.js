const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  list: () => ipcRenderer.invoke('list'),
  password: (id) => ipcRenderer.invoke('password', id),
  state: () => ipcRenderer.invoke('state'),
  connect: (id, password) => ipcRenderer.invoke('connect', id, password),
  code: (code) => ipcRenderer.invoke('code', code),
  disconnect: () => ipcRenderer.invoke('disconnect'),
  dismiss: () => ipcRenderer.invoke('dismiss'),
  dockerOpen: () => ipcRenderer.invoke('docker-open'),
  dockerDownload: () => ipcRenderer.invoke('docker-download'),
  dockerCancel: () => ipcRenderer.invoke('docker-cancel'),
  save: (vpn) => ipcRenderer.invoke('save', vpn),
  remove: (id) => ipcRenderer.invoke('delete', id),
  importFile: () => ipcRenderer.invoke('import'),
  hostsRemove: () => ipcRenderer.invoke('hosts-remove'),
  hostsStatus: () => ipcRenderer.invoke('hosts-status'),
  hostsApply: () => ipcRenderer.invoke('hosts-apply'),
  clipboardText: () => ipcRenderer.invoke('clipboard-text'),
  clipboardWrite: (text) => ipcRenderer.invoke('clipboard-write', text),
  updateInfo: () => ipcRenderer.invoke('update-info'),
  updateGo: () => ipcRenderer.invoke('update-go'),
  updatePage: () => ipcRenderer.invoke('update-page'),
  onUpdate: (fn) => ipcRenderer.on('update', (_e, u) => fn(u)),
  lang: () => ipcRenderer.invoke('lang'),
  setLang: (l) => ipcRenderer.invoke('set-lang', l),
  openSite: (site) => ipcRenderer.invoke('open-site', site),
  onState: (fn) => ipcRenderer.on('state', (_e, s) => fn(s)),
});
